def build_product_records() -> list[dict]:
    """Build normalized product dicts with auto-generated SKUs, Thai 885 barcodes, and image URLs."""
    records: list[dict] = []
    for idx, item in enumerate(ALL_PRODUCTS, start=1):
        seller, name, cat, brand, price, stock, unit, pack_qty, tags, desc, photo_override = item
        photo_id = photo_override if photo_override is not None else CAT_PHOTOS.get(cat)
        # Keep Bamboo cutting board image optional only if explicitly None AND original item; otherwise use category photo
        if name == "Bamboo cutting board":
            image_url = IMG_BASE.format(CAT_PHOTOS["Kitchen & Dining"])
        else:
            image_url = IMG_BASE.format(photo_id) if photo_id else None
        sku = f"FDE-{idx:04d}"
        barcode = f"885{idx:010d}"
        records.append({
            "product_id": idx,
            "seller": seller,
            "name": name,
            "category": cat,
            "brand": brand,
            "price": price,
            "stock_qty": stock,
            "unit": unit,
            "pack_qty": pack_qty,
            "tags": list(tags),
            "description": desc,
            "image_url": image_url,
            "sku": sku,
            "barcode": barcode,
        })
    return records
